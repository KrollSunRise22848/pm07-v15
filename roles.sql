-- Выдача прав для варианта 15. Пароли заменены заглушками.
CREATE DATABASE IF NOT EXISTS pm07_v15 CHARACTER SET utf8mb4;
CREATE DATABASE IF NOT EXISTS pm07_v15_restore CHARACTER SET utf8mb4;

CREATE USER IF NOT EXISTS 'admin'@'%'    IDENTIFIED BY 'ADMIN_PASSWORD';
CREATE USER IF NOT EXISTS 'app_user'@'%' IDENTIFIED BY 'APP_PASSWORD';
CREATE USER IF NOT EXISTS 'readonly'@'%' IDENTIFIED BY 'READ_PASSWORD';

GRANT ALL PRIVILEGES ON pm07_v15.*         TO 'admin'@'%';
GRANT ALL PRIVILEGES ON pm07_v15_restore.* TO 'admin'@'%';
GRANT SELECT,INSERT,UPDATE,DELETE ON pm07_v15.* TO 'app_user'@'%';
GRANT SELECT ON pm07_v15.* TO 'readonly'@'%';
